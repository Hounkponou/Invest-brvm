-- =====================================================================
-- pipeline_runs : historique d'exécution du pipeline (observabilité)
-- Chaque run (train/predict/evaluate/gemini/export) y insère une ligne :
-- tâche, statut, durée, détails (jsonb), horodatage.
-- À exécuter UNE fois dans Supabase -> SQL Editor.
-- =====================================================================

create table if not exists public.pipeline_runs (
  id          bigint generated by default as identity primary key,
  task        text not null,          -- train | predict | evaluate | gemini | export
  status      text not null,          -- success | failed
  duration_s  numeric,                -- durée du run en secondes
  detail      jsonb,                  -- { engine, result, error... }
  run_at      timestamptz not null default now()
);

create index if not exists pipeline_runs_run_at_idx on public.pipeline_runs (run_at desc);
create index if not exists pipeline_runs_task_idx   on public.pipeline_runs (task, run_at desc);

-- Sécurité : lecture pour les utilisateurs connectés (dashboard de statut) ;
-- écriture réservée au pipeline (clé service_role, qui bypasse la RLS) -> aucune
-- policy d'INSERT pour les utilisateurs.
alter table public.pipeline_runs enable row level security;

create policy "read_pipeline_runs" on public.pipeline_runs
  for select to authenticated using (true);
